use std::fmt;

use sha1::{Digest, Sha1};

const MUSIC_ORIGIN: &str = "https://music.youtube.com";
const YOUTUBE_DOMAIN: &str = "youtube.com";
const HTTP_ONLY_PREFIX: &str = "#HttpOnly_";
const SAPISID_NAMES: [&str; 2] = ["SAPISID", "__Secure-3PAPISID"];

#[derive(Clone, PartialEq, Eq)]
pub struct MusicAuth {
    cookie_header: String,
    sapisid: String,
}

impl fmt::Debug for MusicAuth {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str("MusicAuth { .. }")
    }
}

struct NetscapeCookie<'text> {
    domain: &'text str,
    expires_at: u64,
    name: &'text str,
    value: &'text str,
}

impl MusicAuth {
    pub fn from_netscape_cookies(text: &str, now_unix: u64) -> Option<Self> {
        let mut cookies: Vec<(&str, &str)> = Vec::new();
        let live_youtube_cookies = text
            .lines()
            .filter_map(netscape_cookie)
            .filter(|cookie| is_youtube_domain(cookie.domain))
            .filter(|cookie| cookie.expires_at == 0 || cookie.expires_at > now_unix);
        for cookie in live_youtube_cookies {
            cookies.retain(|(name, _)| *name != cookie.name);
            cookies.push((cookie.name, cookie.value));
        }
        let sapisid = SAPISID_NAMES.iter().find_map(|wanted| {
            cookies
                .iter()
                .find(|(name, value)| name == wanted && !value.is_empty())
                .map(|(_, value)| (*value).to_owned())
        })?;
        let cookie_header = cookies
            .iter()
            .map(|(name, value)| format!("{name}={value}"))
            .collect::<Vec<_>>()
            .join("; ");
        Some(Self {
            cookie_header,
            sapisid,
        })
    }

    pub fn cookie_header(&self) -> &str {
        &self.cookie_header
    }

    pub fn authorization(&self, now_unix: u64) -> String {
        let signed = format!("{now_unix} {} {MUSIC_ORIGIN}", self.sapisid);
        let digest = Sha1::digest(signed.as_bytes());
        let hex: String = digest.iter().map(|byte| format!("{byte:02x}")).collect();
        format!("SAPISIDHASH {now_unix}_{hex}")
    }
}

fn netscape_cookie(line: &str) -> Option<NetscapeCookie<'_>> {
    let line = line.strip_prefix(HTTP_ONLY_PREFIX).unwrap_or(line);
    if line.starts_with('#') || line.trim().is_empty() {
        return None;
    }
    let fields: Vec<&str> = line.trim_end_matches(['\r', '\n']).split('\t').collect();
    let [domain, _, _, _, expires_at, name, value] = fields.as_slice() else {
        return None;
    };
    let expires_at = expires_at
        .trim()
        .parse()
        .inspect_err(|error| tracing::debug!("skipping the cookie {name}: bad expiry: {error}"))
        .ok()?;
    Some(NetscapeCookie {
        domain,
        expires_at,
        name,
        value,
    })
}

fn is_youtube_domain(domain: &str) -> bool {
    let domain = domain.trim_start_matches('.');
    domain == YOUTUBE_DOMAIN
        || domain
            .strip_suffix(YOUTUBE_DOMAIN)
            .is_some_and(|subdomain| subdomain.ends_with('.'))
}

#[cfg(test)]
mod tests {
    use super::*;

    const NOW: u64 = 1_700_000_000;
    const FIXTURE: &str = "# Netscape HTTP Cookie File\n\
        # This file is generated by yt-dlp.  Do not edit.\n\
        \n\
        .youtube.com\tTRUE\t/\tTRUE\t4102444800\tSAPISID\tfixture-sapisid\n\
        #HttpOnly_.youtube.com\tTRUE\t/\tTRUE\t4102444800\tSID\tfixture-sid\n\
        .youtube.com\tTRUE\t/\tTRUE\t1000\tEXPIRED\told\n\
        .google.com\tTRUE\t/\tTRUE\t4102444800\tNID\tnot-for-youtube\n\
        .notyoutube.com\tTRUE\t/\tTRUE\t4102444800\tEVIL\tnope\n\
        music.youtube.com\tFALSE\t/\tTRUE\t0\tPREF\tf6=8\n\
        broken line without tabs\n";

    #[test]
    fn netscape_files_give_youtube_cookies_only() {
        let auth = MusicAuth::from_netscape_cookies(FIXTURE, NOW).unwrap();
        assert_eq!(
            auth.cookie_header(),
            "SAPISID=fixture-sapisid; SID=fixture-sid; PREF=f6=8"
        );
    }

    #[test]
    fn requests_are_signed_with_the_sapisid_hash() {
        let auth = MusicAuth::from_netscape_cookies(FIXTURE, NOW).unwrap();
        assert_eq!(
            auth.authorization(NOW),
            "SAPISIDHASH 1700000000_60fad894b307bdc3e507215af83e560115486d0f"
        );
    }

    #[test]
    fn the_secure_3papisid_cookie_is_used_when_sapisid_is_missing() {
        let text = ".youtube.com\tTRUE\t/\tTRUE\t0\t__Secure-3PAPISID\tfixture-3papisid\n";
        let auth = MusicAuth::from_netscape_cookies(text, NOW).unwrap();
        assert_eq!(
            auth.authorization(NOW),
            "SAPISIDHASH 1700000000_20d2b29e03d20b2984984d04cbc4a731f8ab07f1"
        );
    }

    #[test]
    fn files_without_a_session_give_no_sign_in() {
        let anonymous = ".youtube.com\tTRUE\t/\tTRUE\t0\tYSC\tvisitor\n";
        assert_eq!(MusicAuth::from_netscape_cookies(anonymous, NOW), None);
        assert_eq!(MusicAuth::from_netscape_cookies("", NOW), None);
    }

    #[test]
    fn given_a_cookie_with_a_malformed_expiry_it_is_skipped() {
        let text = ".youtube.com\tTRUE\t/\tTRUE\tsoon\tSAPISID\tfixture-sapisid\n\
            .youtube.com\tTRUE\t/\tTRUE\t0\tPREF\tf6=8\n";
        assert_eq!(MusicAuth::from_netscape_cookies(text, NOW), None);
    }

    #[test]
    fn debug_output_never_shows_cookies() {
        let auth = MusicAuth::from_netscape_cookies(FIXTURE, NOW).unwrap();
        assert_eq!(format!("{auth:?}"), "MusicAuth { .. }");
    }
}
